function athensSlot(ymd: string, hour: number, minute: number, durationMin: number): {
  startsAt: string;
  endsAt: string;
} {
  const startsAt = athensCivilToUtcIso(ymd, hour, minute);
  const endsAt = addMinutesToIso(startsAt, durationMin);
  return { startsAt, endsAt };
}

