function enrichDemoAppointment(
  a: SecretaryAppointment | (Omit<SecretaryAppointment, "parentLabel" | "reminderStatus"> & {
    parentLabel?: string | null;
    reminderStatus?: AppointmentReminderStatus;
  })
): SecretaryAppointment {
  const type = appointmentTypeByCode(a.appointmentTypeCode);
  return {
    ...a,
    parentLabel: a.parentLabel ?? parentLabelForChild(a.childId),
    reminderStatus: a.reminderStatus ?? (a.reminderAt ? "scheduled" : "pending"),
    appointmentTypeLabel: type?.nameEl ?? a.appointmentTypeLabel,
  };
}

